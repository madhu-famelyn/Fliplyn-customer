import React, { useEffect, useState, useCallback, useRef } from "react";
import axios from "axios";
import { useAuth } from "../../AuthContex/ContextAPI";
import { useNavigate } from "react-router-dom";
import * as XLSX from "xlsx";
import { exportSheetToPdf } from "../../../utils/exportSheetToPdf";
import "./DailyOrderSummaryReport.css";

const API_BASE =
  process.env.REACT_APP_API_URL ||
  (typeof window !== "undefined" && window.location.hostname === "localhost"
    ? "http://localhost:8000"
    : "https://admin-aged-field-2794.fly.dev");

export default function DailyOrderSummaryReport() {
  const { user } = useAuth();
  const navigate = useNavigate();

  const [stalls, setStalls] = useState([]);
  const [selectedStall, setSelectedStall] = useState("all");
  const [period, setPeriod] = useState("this_month");
  const [startDate, setStartDate] = useState("");
  const [endDate, setEndDate] = useState("");

  const [loading, setLoading] = useState(false);
  const [exportingPdf, setExportingPdf] = useState(false);
  const [reportData, setReportData] = useState(null);
  const [errorMsg, setErrorMsg] = useState("");

  const reportRef = useRef(null);

  /* ── 1. Fetch Outlets / Stalls for this Manager's Building ── */
  useEffect(() => {
    if (!user?.building_id) return;
    axios
      .get(`${API_BASE}/stalls/building/${user.building_id}`)
      .then((res) => setStalls(res.data || []))
      .catch((err) => console.error("Error fetching stalls:", err));
  }, [user]);

  /* ── 2. Fetch Report Data ── */
  const fetchReport = useCallback(async () => {
    setLoading(true);
    setErrorMsg("");

    try {
      const params = new URLSearchParams();
      if (user?.building_id) params.append("building_id", user.building_id);
      if (selectedStall && selectedStall !== "all") params.append("stall_id", selectedStall);
      params.append("period", period);
      params.append("payment_type", "prepaid");
      params.append("apply_fee", "true");

      if (period === "custom") {
        if (!startDate || !endDate) {
          setErrorMsg("Please select both start and end dates.");
          setLoading(false);
          return;
        }
        params.append("start_date", startDate);
        params.append("end_date", endDate);
      }

      params.append("generated_by", "Sai Ram");

      const res = await axios.get(`${API_BASE}/orders/daily-summary?${params.toString()}`);
      setReportData(res.data);
    } catch (err) {
      console.error("Error loading daily order summary:", err);
      setErrorMsg("Failed to load daily order summary report. Please try again.");
    } finally {
      setLoading(false);
    }
  }, [user, selectedStall, period, startDate, endDate]);

  // Initial load & when parameters change
  useEffect(() => {
    fetchReport();
  }, [fetchReport]);

  /* ── 3. Export to Excel (Exact Same Formatted Sheet as Displayed) ── */
  const handleExportExcel = () => {
    if (!reportData || !reportData.rows || reportData.rows.length === 0) {
      alert("No report data available to export.");
      return;
    }

    const wsData = [
      ["Order Summary"],
      [],
      ["Business Name:", reportData.business_name || "Gowra (Parent)"],
      ["Summary By:", reportData.summary_by || "DAY"],
      ["Period:", reportData.period || "6 Months"],
      ["Report Generated On:", reportData.report_generated_on],
      ["Report Generated By:", "Sai Ram"],
      [],
      [
        "Date",
        "No. of Orders",
        "Net Amount",
        "Discount",
        "Charges",
        "Tax",
        "Round Off",
        "Total Amount",
      ],
    ];

    reportData.rows.forEach((row) => {
      wsData.push([
        row.date,
        row.no_of_orders,
        Number(row.net_amount || 0),
        Number(row.discount || 0),
        Number(row.charges || 0),
        Number(row.tax || 0),
        Number(row.round_off || 0),
        Number(row.total_amount || 0),
      ]);
    });

    const ws = XLSX.utils.aoa_to_sheet(wsData);
    ws["!cols"] = [
      { wch: 18 },
      { wch: 15 },
      { wch: 16 },
      { wch: 12 },
      { wch: 12 },
      { wch: 14 },
      { wch: 14 },
      { wch: 16 },
    ];

    const wb = XLSX.utils.book_new();
    XLSX.utils.book_append_sheet(wb, ws, "Order Summary");

    const safeName = (reportData.business_name || "Order_Summary")
      .replace(/[^a-zA-Z0-9_-]/g, "_");
    XLSX.writeFile(wb, `${safeName}_Daily_Sales_Report.xlsx`);
  };

  /* ── 4. Direct PDF Download (Pixel-Perfect Same Format as Displayed) ── */
  const handleDownloadPDF = async () => {
    if (!reportRef.current || !reportData) {
      alert("No report data available to export.");
      return;
    }

    setExportingPdf(true);
    try {
      const safeName = (reportData.business_name || "Order_Summary")
        .replace(/[^a-zA-Z0-9_-]/g, "_");
      await exportSheetToPdf(reportRef.current, `${safeName}_Order_Summary_Report.pdf`);
    } catch (err) {
      console.error("PDF generation failed:", err);
      alert("Failed to generate PDF. Please try again.");
    } finally {
      setExportingPdf(false);
    }
  };

  const formatNumber = (val) => {
    if (val === null || val === undefined) return "0.0";
    const num = Number(val);
    if (isNaN(num)) return "0.0";
    return num % 1 === 0 ? `${num}.0` : num.toFixed(2);
  };

  return (
    <div className="daily-summary-page-container">
      {/* ── Screen-Only Controls Bar ── */}
      <div className="daily-summary-controls-card no-print">
        <div className="daily-summary-controls-left">
          <button
            className="daily-summary-back-btn"
            onClick={() => navigate("/manager-stalls")}
            title="Back to Outlets Dashboard"
          >
            ← Back
          </button>

          {/* Period Dropdown */}
          <select
            className="daily-summary-select"
            value={period}
            onChange={(e) => setPeriod(e.target.value)}
          >
            <option value="this_month">This Month (Default)</option>
            <option value="6_months">6 Months</option>
            <option value="last_month">Last Month</option>
            <option value="this_week">This Week</option>
            <option value="today">Today</option>
            <option value="custom">Custom Date Range</option>
          </select>

          {/* Custom Date Pickers */}
          {period === "custom" && (
            <>
              <input
                type="date"
                className="daily-summary-date-input"
                value={startDate}
                onChange={(e) => setStartDate(e.target.value)}
              />
              <span style={{ color: "#64748b", fontSize: "13px" }}>to</span>
              <input
                type="date"
                className="daily-summary-date-input"
                value={endDate}
                onChange={(e) => setEndDate(e.target.value)}
              />
            </>
          )}

          {/* Stalls / Outlets Dropdown */}
          <select
            className="daily-summary-select"
            value={selectedStall}
            onChange={(e) => setSelectedStall(e.target.value)}
          >
            <option value="all">🏢 All Outlets (Parent)</option>
            {stalls.map((s) => (
              <option key={s.id || s.stall_id} value={s.id || s.stall_id}>
                🏪 {s.name || s.stall_name}
              </option>
            ))}
          </select>

          <button
            className="daily-summary-btn-primary"
            onClick={fetchReport}
            disabled={loading}
          >
            {loading ? "Loading…" : "🔍 Generate Report"}
          </button>
        </div>

        <div className="daily-summary-controls-right">
          <button
            className="daily-summary-btn-secondary"
            onClick={handleExportExcel}
            title="Download Excel Sheet with exact same format"
          >
            📥 Export Excel
          </button>
          <button
            className="daily-summary-btn-print"
            onClick={handleDownloadPDF}
            disabled={exportingPdf}
            title="Download PDF directly with exact same format"
          >
            {exportingPdf ? "⏳ Generating PDF…" : "📄 Save as PDF"}
          </button>
        </div>
      </div>

      {errorMsg && (
        <div
          className="no-print"
          style={{
            maxWidth: "960px",
            margin: "0 auto 16px auto",
            padding: "12px 16px",
            backgroundColor: "#fee2e2",
            border: "1px solid #f87171",
            borderRadius: "6px",
            color: "#b91c1c",
            fontSize: "14px",
          }}
        >
          {errorMsg}
        </div>
      )}

      {/* ── Document Sheet (Identical to Reference Image) ── */}
      <div className="daily-summary-document-sheet" ref={reportRef}>
        {loading ? (
          <div className="daily-summary-loader-wrapper">
            <div className="daily-summary-spinner" />
            <span style={{ fontSize: "14px", color: "#64748b" }}>
              Generating Order Summary Report…
            </span>
          </div>
        ) : reportData ? (
          <>
            {/* Centered Document Title */}
            <h1 className="daily-summary-doc-title">Order Summary</h1>

            {/* Metadata Info Block */}
            <div className="daily-summary-meta-block">
              <div className="daily-summary-meta-row">
                <span className="daily-summary-meta-label">Business Name:</span>
                <span className="daily-summary-meta-value">
                  {reportData.business_name || "Gowra (Parent)"}
                </span>
              </div>
              <div className="daily-summary-meta-row">
                <span className="daily-summary-meta-label">Summary By:</span>
                <span className="daily-summary-meta-value">
                  {reportData.summary_by || "DAY"}
                </span>
              </div>
              <div className="daily-summary-meta-row">
                <span className="daily-summary-meta-label">Period:</span>
                <span className="daily-summary-meta-value">
                  {reportData.period || "6 Months"}
                </span>
              </div>
              <div className="daily-summary-meta-row">
                <span className="daily-summary-meta-label">
                  Report Generated On:
                </span>
                <span className="daily-summary-meta-value">
                  {reportData.report_generated_on}
                </span>
              </div>
              <div className="daily-summary-meta-row">
                <span className="daily-summary-meta-label">
                  Report Generated By:
                </span>
                <span className="daily-summary-meta-value">
                  Sai Ram
                </span>
              </div>
            </div>

            {/* Table */}
            <div className="daily-summary-table-wrapper">
              <table className="daily-summary-report-table">
                <thead>
                  <tr>
                    <th>Date</th>
                    <th>No. of Orders</th>
                    <th>Net Amount</th>
                    <th>Discount</th>
                    <th>Charges</th>
                    <th>Tax</th>
                    <th>Round Off</th>
                    <th>Total Amount</th>
                  </tr>
                </thead>
                <tbody>
                  {reportData.rows && reportData.rows.length > 0 ? (
                    reportData.rows.map((row, idx) => (
                      <tr key={idx}>
                        <td>{row.date}</td>
                        <td>{row.no_of_orders}</td>
                        <td>{formatNumber(row.net_amount)}</td>
                        <td>{formatNumber(row.discount)}</td>
                        <td>{formatNumber(row.charges)}</td>
                        <td>{formatNumber(row.tax)}</td>
                        <td>{formatNumber(row.round_off)}</td>
                        <td>{formatNumber(row.total_amount)}</td>
                      </tr>
                    ))
                  ) : (
                    <tr>
                      <td colSpan="8" className="daily-summary-empty-msg">
                        No orders recorded for this period.
                      </td>
                    </tr>
                  )}
                </tbody>
              </table>
            </div>
          </>
        ) : (
          <div className="daily-summary-empty-msg">
            Click "Generate Report" to view sales summary.
          </div>
        )}
      </div>
    </div>
  );
}
